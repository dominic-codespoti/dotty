    public static TheoryData<string, string, string, string> Rows()
    {
        var data = new TheoryData<string, string, string, string>();
        for (int i = 0; i < Table.GetLength(0); i++)
            data.Add(Table[i, 0], Table[i, 1], Table[i, 2], Table[i, 3]);
        return data;
    }

    [Fact]
    public void TableHasAtLeast150Rows()
    {
        Assert.True(Table.GetLength(0) >= 150, $"{Table.GetLength(0)} rows");
    }

    [Theory]
    [MemberData(nameof(Rows))]
    public void LegacyEncodingMatchesTable(string key, string modifiers, string modes, string expected)
    {
        var terminalKey = Enum.Parse<TerminalKey>(key);
        var terminalModifiers = TerminalKeyModifiers.None;
        foreach (string part in modifiers.Split('|'))
            terminalModifiers |= Enum.Parse<TerminalKeyModifiers>(part);
        var encoder = new TerminalInputEncoder();
        Span<byte> buffer = stackalloc byte[32];

        int length = encoder.Encode(terminalKey, terminalModifiers, buffer,
            keypadApplicationMode: modes == "DECKPAM",
            applicationCursorKeys: modes == "DECCKM",
            backarrowSendsBackspace: modes == "DECBKM");

        Assert.Equal(expected, Encoding.Latin1.GetString(buffer[..length]));
    }
