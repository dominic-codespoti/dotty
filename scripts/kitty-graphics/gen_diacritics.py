#!/usr/bin/env python3
"""Regenerates src/Dotty.Terminal/Graphics/Diacritics.cs.

The table is the list of combining marks the Kitty graphics protocol uses to encode row/column/high-byte
indices in Unicode-placeholder cells (297 entries, ascending, all canonical combining class 230, all
assigned in Unicode 6.0). It is kept here as ranges so it can be corrected in one place; the script
verifies the structural properties before writing. Usage: gen_diacritics.py [--check]
"""
import sys
import unicodedata

RANGES = """0305 030D 030E 0310 0312 033D-033F 0346 034A-034C 0350-0352 0357 035B 0363-036F 0483-0487
0592-0595 0597-0599 059C-05A1 05A8-05A9 05AB-05AC 05AF 05C4 0610-0617 0657-065B 065D-065E 06D6-06DC
06DF-06E2 06E4 06E7-06E8 06EB-06EC 0730 0732-0733 0735-0736 073A 073D 073F-0741 0743 0745 0747
0749-074A 07EB-07F1 07F3 0816-0819 081B-0823 0825-0827 0829-082D 0951 0953-0954 0F82-0F83 0F86-0F87
135D-135F 17DD 193A 1A17 1A75-1A7C 1B6B 1B6D-1B73 1CD0-1CD2 1CDA-1CDB 1CE0 1DC0-1DC1 1DC3-1DC9
1DCB-1DCC 1DD1-1DE6 1DFE 20D0-20D1 20D4-20D7 20DB-20DC 20E1 20E7 20E9 20F0 2CEF-2CF1 2DE0-2DFF
A66F A67C-A67D A6F0-A6F1 A8E0-A8F1 AAB0 AAB2-AAB3 AAB7-AAB8 AABE-AABF AAC1 FE20-FE26 10A0F 10A38
1D185-1D189 1D1AA-1D1AD 1D242-1D244"""


def codepoints():
    out = []
    for tok in RANGES.split():
        a, _, b = tok.partition("-")
        lo = int(a, 16)
        hi = int(b, 16) if b else lo
        out.extend(range(lo, hi + 1))
    return out


def main():
    cps = codepoints()
    assert len(cps) == 297, len(cps)
    assert cps == sorted(set(cps))
    assert cps[:10] == [0x305, 0x30D, 0x30E, 0x310, 0x312, 0x33D, 0x33E, 0x33F, 0x346, 0x34A]
    assert cps[-1] == 0x1D244
    for cp in cps:
        assert unicodedata.combining(chr(cp)) == 230, hex(cp)
    lines = []
    for i in range(0, len(cps), 8):
        lines.append("        " + ", ".join(f"0x{c:X}" for c in cps[i:i + 8]) + ",")
    src = f"""// <auto-generated> by scripts/kitty-graphics/gen_diacritics.py - edit the script, not this file. </auto-generated>
namespace Dotty.Terminal.Graphics;

/// <summary>
/// The 297 combining marks of the Kitty graphics protocol's row/column/high-byte table: the mark at
/// position <c>n</c> encodes the number <c>n</c>. Ascending, so decoding is a binary search.
/// </summary>
internal static class Diacritics
{{
    private static readonly int[] s_codepoints =
    [
{chr(10).join(lines)}
    ];

    /// <summary>Number of entries (the largest encodable index is <c>Count - 1</c>).</summary>
    public static int Count => s_codepoints.Length;

    /// <summary>The code point encoding <paramref name="index"/>, or -1 when out of range.</summary>
    public static int CodepointAt(int index) => (uint)index < (uint)s_codepoints.Length ? s_codepoints[index] : -1;

    /// <summary>The index encoded by <paramref name="codepoint"/>, or -1 when it is not in the table.</summary>
    public static int IndexOf(int codepoint)
    {{
        int i = System.Array.BinarySearch(s_codepoints, codepoint);
        return i >= 0 ? i : -1;
    }}
}}
"""
    if "--check" in sys.argv:
        print("ok", len(cps))
        return
    open("src/Dotty.Terminal/Graphics/Diacritics.cs", "w", newline="\n").write(src)


main()
